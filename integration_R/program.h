#ifndef POSEIDON16_PROGRAM_H
#define POSEIDON16_PROGRAM_H

#include <cstdint>
#include <vector>

/*
    ============================================================
                    Poseidon16 Demo Program
    ============================================================

    This program demonstrates arithmetic, logic, comparison,
    multiplication, division, and remainder operations.

    Example scenario:

        R1 = 6
        R2 = 4

        R3  = R1 + R2       = 10
        R4  = R1 - R2       = 2
        R5  = R1 * R2       = 24
        R6  = R5 / R3       = 2
        R7  = R5 % R3       = 4

        R8  = R1 & R2       = 4
        R9  = R1 | R2       = 6

        R10 = R3 & 7        = 2
        R11 = R4 | 1        = 3

        R12 = (R2 < R1)     = 1

    ============================================================
    Instruction List
    ============================================================

    Address   Machine Code    Assembly

    0x0000    0x8106          ADDI R1,  R0, 6
    0x0002    0x8204          ADDI R2,  R0, 4

    0x0004    0x0312          ADD  R3,  R1, R2
    0x0006    0x1412          SUB  R4,  R1, R2

    0x0008    0x5512          MUL  R5,  R1, R2
    0x000A    0x6653          DIV  R6,  R5, R3
    0x000C    0x7753          REM  R7,  R5, R3

    0x000E    0x2812          AND  R8,  R1, R2
    0x0010    0x3912          OR   R9,  R1, R2

    0x0012    0x9A37          ANDI R10, R3, 7
    0x0014    0xAB41          ORI  R11, R4, 1

    0x0016    0x4C21          SLT  R12, R2, R1


    ============================================================
    Expected Final Register Values
    ============================================================

    R0  = 0
    R1  = 6
    R2  = 4
    R3  = 10
    R4  = 2
    R5  = 24
    R6  = 2
    R7  = 4
    R8  = 4
    R9  = 6
    R10 = 2
    R11 = 3
    R12 = 1
    R13 = 0
    R14 = 0
    R15 = 0

    ============================================================
*/

// Instructions are stored as bytes in Big-Endian order.
//
// Example:
//     0x8106
//
// memory[address]     = 0x81
// memory[address + 1] = 0x06

inline const std::vector<std::uint8_t> program = {

    // ------------------------------------------------------------
    // Initialize values
    // ------------------------------------------------------------

    0x81, 0x06,     // ADDI R1, R0, 6
    0x82, 0x04,     // ADDI R2, R0, 4


    // ------------------------------------------------------------
    // Basic arithmetic
    // ------------------------------------------------------------

    0x03, 0x12,     // ADD  R3, R1, R2      -> 10

    0x14, 0x12,     // SUB  R4, R1, R2      -> 2


    // ------------------------------------------------------------
    // M-extension
    // ------------------------------------------------------------

    0x55, 0x12,     // MUL  R5, R1, R2      -> 24

    0x66, 0x53,     // DIV  R6, R5, R3      -> 24 / 10 = 2

    0x77, 0x53,     // REM  R7, R5, R3      -> 24 % 10 = 4


    // ------------------------------------------------------------
    // Register logic
    // ------------------------------------------------------------

    0x28, 0x12,     // AND  R8, R1, R2      -> 6 & 4 = 4

    0x39, 0x12,     // OR   R9, R1, R2      -> 6 | 4 = 6


    // ------------------------------------------------------------
    // Immediate logic
    // ------------------------------------------------------------

    0x9A, 0x37,     // ANDI R10, R3, 7      -> 10 & 7 = 2

    0xAB, 0x41,     // ORI  R11, R4, 1      -> 2 | 1 = 3


    // ------------------------------------------------------------
    // Comparison
    // ------------------------------------------------------------

    0x4C, 0x21      // SLT  R12, R2, R1     -> 4 < 6 = 1
};

#endif // POSEIDON16_PROGRAM_H